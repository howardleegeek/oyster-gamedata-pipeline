#!/bin/bash
#
# cn_mirror_setup.sh - Configure China vendor mirrors for pip, npm, HuggingFace, nvm, apt
# Usage:
#   bash bin/cn_mirror_setup.sh           # set pip+npm+HF+nvm (safe)
#   bash bin/cn_mirror_setup.sh --apt     # also rewrite apt sources
#   bash bin/cn_mirror_setup.sh --revert  # restore original configs

set -e

BACKUP_DIR="$HOME/.cn_mirror_backup"
BASHRC="$HOME/.bashrc"
BASHRC_BACKUP="$BACKUP_DIR/.bashrc.bak"
APT_SOURCES="/etc/apt/sources.list"
APT_SOURCES_BACKUP="$BACKUP_DIR/sources.list.bak"

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

log_info() {
    echo -e "${GREEN}[INFO]${NC} $1"
}

log_warn() {
    echo -e "${YELLOW}[WARN]${NC} $1"
}

log_error() {
    echo -e "${RED}[ERROR]${NC} $1"
}

# Ensure backup directory exists
ensure_backup_dir() {
    if [[ ! -d "$BACKUP_DIR" ]]; then
        mkdir -p "$BACKUP_DIR"
    fi
}

# Backup a file if not already backed up
backup_file() {
    local file="$1"
    local backup="$2"
    if [[ -f "$file" ]]; then
        if [[ ! -f "$backup" ]]; then
            cp "$file" "$backup"
            log_info "Backed up $file to $backup"
        fi
    fi
}

# Restore from backup
restore_file() {
    local backup="$1"
    local file="$2"
    if [[ -f "$backup" ]]; then
        cp "$backup" "$file"
        log_info "Restored $file from $backup"
    else
        log_warn "No backup found for $file"
    fi
}

# Configure pip to use Tsinghua mirror
configure_pip() {
    log_info "Configuring pip to use Tsinghua mirror..."
    pip config set global.index-url https://pypi.tuna.tsinghua.edu.cn/simple 2>/dev/null || \
        pip3 config set global.index-url https://pypi.tuna.tsinghua.edu.cn/simple 2>/dev/null || \
        log_warn "pip config set failed, trying legacy method..."
    
    # Also add to pip.conf if pip command not available
    local pip_conf_dir="$HOME/.config/pip"
    if [[ ! -f "$pip_conf_dir/pip.conf" ]] && [[ ! -f "$HOME/.pip/pip.conf" ]]; then
        mkdir -p "$pip_conf_dir"
        echo -e "[global]\nindex-url = https://pypi.tuna.tsinghua.edu.cn/simple" > "$pip_conf_dir/pip.conf"
        log_info "Created pip.conf at $pip_conf_dir/pip.conf"
    fi
}

# Configure npm to use Taobao mirror
configure_npm() {
    log_info "Configuring npm to use Taobao mirror..."
    npm config set registry https://registry.npmmirror.com 2>/dev/null || \
        log_warn "npm config set failed"
}

# Configure HuggingFace endpoint
configure_huggingface() {
    log_info "Configuring HuggingFace mirror..."
    ensure_backup_dir
    backup_file "$BASHRC" "$BASHRC_BACKUP"
    
    local hf_line="export HF_ENDPOINT=https://hf-mirror.com"
    
    if grep -q "^export HF_ENDPOINT=" "$BASHRC" 2>/dev/null; then
        sed -i "s|^export HF_ENDPOINT=.*|$hf_line|" "$BASHRC"
        log_info "Updated HF_ENDPOINT in $BASHRC"
    elif ! grep -q "HF_ENDPOINT" "$BASHRC" 2>/dev/null; then
        echo "" >> "$BASHRC"
        echo "# China mirror for HuggingFace" >> "$BASHRC"
        echo "$hf_line" >> "$BASHRC"
        log_info "Added HF_ENDPOINT to $BASHRC"
    fi
    
    # Export for current session
    export HF_ENDPOINT=https://hf-mirror.com
}

# Configure nvm nodejs mirror
configure_nvm() {
    log_info "Configuring nvm nodejs mirror..."
    ensure_backup_dir
    backup_file "$BASHRC" "$BASHRC_BACKUP"
    
    local nvm_line="export NVM_NODEJS_ORG_MIRROR=https://npmmirror.com/mirrors/node/"
    
    if grep -q "^export NVM_NODEJS_ORG_MIRROR=" "$BASHRC" 2>/dev/null; then
        sed -i "s|^export NVM_NODEJS_ORG_MIRROR=.*|$nvm_line|" "$BASHRC"
        log_info "Updated NVM_NODEJS_ORG_MIRROR in $BASHRC"
    elif ! grep -q "NVM_NODEJS_ORG_MIRROR" "$BASHRC" 2>/dev/null; then
        echo "" >> "$BASHRC"
        echo "# China mirror for nvm nodejs" >> "$BASHRC"
        echo "$nvm_line" >> "$BASHRC"
        log_info "Added NVM_NODEJS_ORG_MIRROR to $BASHRC"
    fi
    
    # Export for current session
    export NVM_NODEJS_ORG_MIRROR=https://npmmirror.com/mirrors/node/
}

# Configure apt to use TUNA mirror (Ubuntu)
configure_apt() {
    log_info "Configuring apt sources to use TUNA mirror..."
    
    if [[ $EUID -ne 0 ]]; then
        log_warn "apt configuration requires root privileges. Run with sudo or as root."
        return 1
    fi
    
    ensure_backup_dir
    backup_file "$APT_SOURCES" "$APT_SOURCES_BACKUP"
    
    # Detect Ubuntu version
    local codename
    codename=$(lsb_release -cs 2>/dev/null || grep -oP 'VERSION_CODENAME=\K\w+' /etc/os-release)
    
    if [[ -z "$codename" ]]; then
        log_error "Could not detect Ubuntu codename"
        return 1
    fi
    
    # Create new sources.list with TUNA mirrors
    cat > "$APT_SOURCES" << EOF
# Ubuntu TUNA mirror sources
# Generated by cn_mirror_setup.sh

deb https://mirrors.tuna.tsinghua.edu.cn/ubuntu/ $codename main restricted universe multiverse
deb https://mirrors.tuna.tsinghua.edu.cn/ubuntu/ $codename-updates main restricted universe multiverse
deb https://mirrors.tuna.tsinghua.edu.cn/ubuntu/ $codename-backports main restricted universe multiverse
deb https://mirrors.tuna.tsinghua.edu.cn/ubuntu/ $codename-security main restricted universe multiverse
EOF
    
    log_info "Updated apt sources.list with TUNA mirrors"
    
    # Update apt
    apt-get update 2>/dev/null || log_warn "apt-get update failed"
}

# Revert all configurations
revert_configs() {
    log_info "Reverting all mirror configurations..."
    
    # Revert pip
    log_info "Reverting pip configuration..."
    pip config unset global.index-url 2>/dev/null || true
    pip3 config unset global.index-url 2>/dev/null || true
    rm -f "$HOME/.config/pip/pip.conf" 2>/dev/null || true
    rm -f "$HOME/.pip/pip.conf" 2>/dev/null || true
    
    # Revert npm
    log_info "Reverting npm configuration..."
    npm config delete registry 2>/dev/null || true
    
    # Revert bashrc exports
    if [[ -f "$BASHRC_BACKUP" ]]; then
        cp "$BASHRC_BACKUP" "$BASHRC"
        log_info "Restored $BASHRC from backup"
    else
        # Remove the lines we added
        sed -i '/^# China mirror for/d' "$BASHRC" 2>/dev/null || true
        sed -i '/^export HF_ENDPOINT=/d' "$BASHRC" 2>/dev/null || true
        sed -i '/^export NVM_NODEJS_ORG_MIRROR=/d' "$BASHRC" 2>/dev/null || true
    fi
    
    # Revert apt if backed up
    if [[ -f "$APT_SOURCES_BACKUP" ]]; then
        if [[ $EUID -ne 0 ]]; then
            log_warn "apt revert requires root privileges"
        else
            cp "$APT_SOURCES_BACKUP" "$APT_SOURCES"
            log_info "Restored $APT_SOURCES from backup"
            apt-get update 2>/dev/null || log_warn "apt-get update failed"
        fi
    fi
    
    log_info "Revert complete"
}

# Verify configurations
verify_configs() {
    echo ""
    echo "========================================"
    echo "         Mirror Configuration          "
    echo "========================================"
    echo ""
    
    # Verify pip
    echo ">>> pip config:"
    pip config list 2>/dev/null || pip3 config list 2>/dev/null || echo "  (no pip config found)"
    echo ""
    
    # Verify npm
    echo ">>> npm registry:"
    npm config get registry 2>/dev/null || echo "  (no npm config found)"
    echo ""
    
    # Verify HF_ENDPOINT
    echo ">>> HuggingFace HF_ENDPOINT:"
    if grep -q "^export HF_ENDPOINT=" "$BASHRC" 2>/dev/null; then
        grep "^export HF_ENDPOINT=" "$BASHRC"
    elif [[ -n "$HF_ENDPOINT" ]]; then
        echo "  HF_ENDPOINT=$HF_ENDPOINT"
    else
        echo "  (not set)"
    fi
    echo ""
    
    # Verify NVM_NODEJS_ORG_MIRROR
    echo ">>> nvm NVM_NODEJS_ORG_MIRROR:"
    if grep -q "^export NVM_NODEJS_ORG_MIRROR=" "$BASHRC" 2>/dev/null; then
        grep "^export NVM_NODEJS_ORG_MIRROR=" "$BASHRC"
    elif [[ -n "$NVM_NODEJS_ORG_MIRROR" ]]; then
        echo "  NVM_NODEJS_ORG_MIRROR=$NVM_NODEJS_ORG_MIRROR"
    else
        echo "  (not set)"
    fi
    echo ""
    
    echo "========================================"
    echo "         Verification Complete         "
    echo "========================================"
}

# Main entry point
main() {
    local do_apt=false
    
    for arg in "$@"; do
        case "$arg" in
            --apt)
                do_apt=true
                ;;
            --revert)
                revert_configs
                verify_configs
                exit 0
                ;;
            --help|-h)
                echo "Usage: $0 [--apt|--revert]"
                echo "  (no args)  Configure pip, npm, HuggingFace, nvm mirrors"
                echo "  --apt      Also configure apt sources (requires root)"
                echo "  --revert   Restore original configurations"
                exit 0
                ;;
            *)
                log_error "Unknown option: $arg"
                echo "Use --help for usage information"
                exit 1
                ;;
        esac
    done
    
    # Configure mirrors
    configure_pip
    configure_npm
    configure_huggingface
    configure_nvm
    
    if $do_apt; then
        configure_apt
    fi
    
    # Verify and show results
    verify_configs
    
    log_info "Mirror configuration complete!"
    log_warn "Please restart your shell or run: source $BASHRC"
}

main "$@"
