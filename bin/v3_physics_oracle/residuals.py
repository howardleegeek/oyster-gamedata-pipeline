def r09_keycode_vk_known(rec: dict) -> OracleResult:
    """Verify all keyCode values are known Windows virtual-key codes.

    Args:
        rec: Recording dictionary containing optional "keyCode" field.

    Returns:
        PASS if all keyCode values are recognized VK codes.
        FAIL if any unknown VK codes are found (residual = count of unknown).
        ABSTAIN if keyCode is missing or not a list.
    """
    kc = rec.get("keyCode")
    if not isinstance(kc, list):
        return OracleResult("R09", Verdict.ABSTAIN, None, None, math.nan,
                            "keyCode not list[int]")
    unknown = [c for c in kc if not isinstance(c, int) or c not in KNOWN_VK_CODES]
    if not unknown:
        return OracleResult("R09", Verdict.PASS, "all in VK table", kc, 0.0)
    return OracleResult("R09", Verdict.FAIL, "all in VK table", kc, float(len(unknown)),
                        f"unknown VK codes: {unknown}")


# ---------------------------------------------------------------------------
# R12: fps must be 30 (PRD page 3 spec: "30 fps 录制规范")
# ---------------------------------------------------------------------------

def r12_fps_fixed_30(rec: dict, tolerance: float = 0.5) -> OracleResult:
    fps = rec.get("fps")
    if fps is None:
        return OracleResult("R12", Verdict.ABSTAIN, 30.0, None, math.nan, "missing fps")
    fps = float(fps)
    residual = abs(fps - 30.0)
    if residual <= tolerance:
        return OracleResult("R12", Verdict.PASS, 30.0, fps, residual)
    return OracleResult("R12", Verdict.FAIL, 30.0, fps, residual,
                        f"fps={fps} not 30 ± {tolerance}")


# ---------------------------------------------------------------------------
# R07: mouse_x/y ∈ [0, 1] strictly, mouse_dx/dy ∈ [-1, 1] strictly
# ---------------------------------------------------------------------------

def r07_mouse_range_strict(rec: dict) -> OracleResult:
    """All mouse fields are list[float] (not scalar). Range strict."""
    for axis in ("x", "y"):
        v = rec.get(f"mouse_{axis}")
        if not isinstance(v, list) or len(v) == 0:
            return OracleResult("R07", Verdict.FAIL, "list[float]", v, math.inf,
                                f"mouse_{axis} not list[float] (PRD wire format)")
        x = float(v[0])
        if not (0.0 <= x <= 1.0):
            return OracleResult("R07", Verdict.FAIL, "[0,1]", x,
                                max(abs(x), abs(x - 1.0)),
                                f"mouse_{axis}={x} outside [0,1]")
        d = rec.get(f"mouse_d{axis}")
        if not isinstance(d, list) or len(d) == 0:
            return OracleResult("R07", Verdict.FAIL, "list[float]", d, math.inf,
                                f"mouse_d{axis} not list[float]")
        dx = float(d[0])
        if not (-1.0 <= dx <= 1.0):
            return OracleResult("R07", Verdict.FAIL, "[-1,1]", dx,
                                max(abs(dx), abs(dx - 1.0), abs(dx + 1.0)),
                                f"mouse_d{axis}={dx} outside [-1,1]")
    return OracleResult("R07", Verdict.PASS, "all in spec range", "ok", 0.0)


