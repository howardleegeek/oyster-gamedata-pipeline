#!/usr/bin/env python3
"""Generate a self-contained STATUS.html dashboard from sprint data."""
import argparse
import os
import re
import subprocess
import sys
from datetime import datetime
from typing import Any, Optional


def read_sprint_report(path: str = "SPRINT_REPORT.md") -> dict[str, str]:
    """Parse key-value metrics from SPRINT_REPORT.md."""
    metrics = {}
    if not os.path.isfile(path):
        return metrics
    with open(path, "r") as f:
        for line in f:
            m = re.match(r"-\s+\*\*(.+?)\*\*:\s*(.+)", line)
            if m:
                metrics[m.group(1).strip()] = m.group(2).strip()
    return metrics


def get_git_log() -> list[dict[str, str]]:
    """Return recent git commits as list of dicts."""
    try:
        out = subprocess.check_output(
            ["git", "log", "--pretty=format:%h|%an|%ad|%s", "--date=short", "-20"],
            stderr=subprocess.DEVNULL, text=True,
        )
        commits = []
        for line in out.strip().splitlines():
            parts = line.split("|", 3)
            if len(parts) == 4:
                commits.append({"hash": parts[0], "author": parts[1],
                                "date": parts[2], "subject": parts[3]})
        return commits
    except (subprocess.CalledProcessError, FileNotFoundError):
        return []


def count_test_files(root: str = "src/tests") -> tuple[dict[str, int], int]:
    """Walk test directory and return file counts by extension.

    Args:
        root: Path to the root directory to scan for test files.

    Returns:
        A tuple of (counts, total) where counts is a dict mapping file
        extensions to their occurrence count, and total is the total
        number of files found.
    """
    counts = {}
    total = 0
    if os.path.isdir(root):
        for dirpath, _, filenames in os.walk(root):
            for fn in filenames:
                ext = os.path.splitext(fn)[1] or "(no ext)"
                counts[ext] = counts.get(ext, 0) + 1
                total += 1
    return counts, total


def build_html(
    metrics: dict[str, str],
    commits: list[dict[str, str]],
    file_counts: dict[str, int],
    total_files: int,
) -> str:
    """Return a complete HTML string with inlined CSS."""
    sprint = metrics.get("Sprint", "N/A")
    rows = "".join(
        f"<tr><td>{k}</td><td>{v}</td></tr>" for k, v in metrics.items()
    )
    commit_rows = "".join(
        f"<tr><td><code>{c['hash']}</code></td><td>{c['author']}</td>"
        f"<td>{c['date']}</td><td>{c['subject']}</td></tr>"
        for c in commits
    ) or "<tr><td colspan='4'>No commits found</td></tr>"
    file_rows = "".join(
        f"<tr><td>{ext}</td><td>{cnt}</td></tr>" for ext, cnt in sorted(file_counts.items())
    )
    now = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    return f"""<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8">
<title>Sprint {sprint} Dashboard</title>
<style>
*{{box-sizing:border-box;margin:0;padding:0}}
body{{font-family:-apple-system,BlinkMacSystemFont,'Segoe UI',Roboto,sans-serif;
  background:#f4f6f9;color:#1a1a2e;padding:2rem}}
h1{{font-size:1.8rem;margin-bottom:.3rem}}
h2{{font-size:1.3rem;margin:1.5rem 0 .5rem}}
table{{border-collapse:collapse;width:100%;margin-bottom:1rem;background:#fff;
  border-radius:8px;overflow:hidden;box-shadow:0 1px 3px rgba(0,0,0,.1)}}
th,td{{padding:.75rem 1rem;text-align:left;border-bottom:1px solid #eee}}
th{{background:#f8f9fa;font-weight:600;color:#555}}
tr:last-child td{{border-bottom:none}}
code{{background:#f0f0f0;padding:.2rem .4rem;border-radius:3px;font-size:.9em}}
footer{{margin-top:2rem;color:#777;font-size:.85rem;text-align:center}}
</style></head>
<body>
<h1>Sprint {sprint} Dashboard</h1>
<p>Generated: {now}</p>

<h2>Metrics</h2>
<table><thead><tr><th>Metric</th><th>Value</th></tr></thead>
<tbody>{rows}</tbody></table>

<h2>Recent Commits</h2>
<table><thead><tr><th>Hash</th><th>Author</th><th>Date</th><th>Subject</th></tr></thead>
<tbody>{commit_rows}</tbody></table>

<h2>Test Files</h2>
<table><thead><tr><th>Extension</th><th>Count</th></tr></thead>
<tbody>{file_rows}
<tr><td><strong>Total</strong></td><td><strong>{total_files}</strong></td></tr>
</tbody></table>

<footer>Generated by generate_dashboard.py</footer>
</body></html>"""


def main(argv: Optional[list[str]] = None) -> int:
    """Generate sprint status dashboard.

    Args:
        argv: Command-line arguments (defaults to sys.argv).

    Returns:
        Exit code (0 for success).
    """
    parser = argparse.ArgumentParser(description="Generate sprint status dashboard")
    parser.add_argument("--output", default="STATUS.html", help="Output HTML file path")
    args = parser.parse_args(argv)

    metrics = read_sprint_report()
    commits = get_git_log()
    file_counts, total_files = count_test_files()

    html = build_html(metrics, commits, file_counts, total_files)
    with open(args.output, "w") as f:
        f.write(html)
    print(f"Dashboard written to {args.output} ({len(html)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
