#!/usr/bin/env python3
"""buyer_tarball_make_real.py — D4 integration: take a buyer-spec tarball
that has placeholder video/depth and rebuild it with REAL captures.

Pre-conditions (D1/D2/D3 must have landed on main):
  - bin/depth_anything_v2_inference.py provides infer_depth_for_video()
  - bin/screen_capture_recorder.py provides record_screen_region()
  - bin/paper_server_start.sh boots a healthy Paper server

Usage:
  python3 bin/buyer_tarball_make_real.py \
      --in-tarball  /tmp/oyster_buyer_mac1_full.tar.gz \
      --out-tarball /tmp/oyster_buyer_REAL.tar.gz \
      --capture-region 0,0,1920,1080 \
      --capture-duration 300

Steps:
  1. Extract input tarball to a tmp staging dir.
  2. Replace video.mp4 with real screen capture (D2).
  3. Replace depth/*.exr with real DepthAnything inference on the new video (D1).
  4. Recompute SHA256SUMS.
  5. Rewrite README.md with truthful "all real" disclosure.
  6. Repack.

Howard 2026-05-06 Iron Law: NO PLACEHOLDER. Every file in the output
tarball is captured or inferred from real data. If any step fails, abort.
NEVER silently fall back to the placeholder.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path
from typing import Any


def _sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def _replace_video(staging: Path, *, region: tuple[int, int, int, int], duration: float) -> dict:
    """Step 2 — real screen capture, replace video.mp4."""
    from bin.screen_capture_recorder import record_screen_region  # noqa: PLC0415

    target = staging / "video.mp4"
    if target.exists():
        target.unlink()

    info = record_screen_region(target, duration_sec=duration, fps=30, region=region)
    if not target.exists() or target.stat().st_size < 100_000:
        raise RuntimeError(f"video capture produced unusably small file: {target}")
    return info


def _replace_depth(staging: Path) -> dict:
    """Step 3 — real DepthAnything inference, replace depth/."""
    from bin.depth_anything_v2_inference import infer_depth_for_video  # noqa: PLC0415

    video = staging / "video.mp4"
    depth_dir = staging / "depth"

    if depth_dir.exists():
        shutil.rmtree(depth_dir)

    manifest = infer_depth_for_video(video, depth_dir, model_variant="vits", device="cpu")
    if len(manifest) < 30:
        raise RuntimeError(f"depth inference produced too few frames: {len(manifest)}")
    return {"frames_inferred": len(manifest)}


def _recompute_sha256sums(staging: Path) -> None:
    """Step 4 — overwrite SHA256SUMS with current file hashes."""
    sumfile = staging / "SHA256SUMS"
    lines: list[str] = []
    for path in sorted(staging.rglob("*")):
        if path.is_file() and path.name != "SHA256SUMS":
            rel = path.relative_to(staging)
            lines.append(f"{_sha256_file(path)}  {rel}\n")
    sumfile.write_text("".join(lines))


def _write_truthful_readme(staging: Path, *, capture_info: dict, depth_info: dict) -> None:
    """Step 5 — write README.md with honest disclosure of real capture provenance."""
    readme = staging / "README.md"
    content = f"""# Oyster Buyer Spec — REAL Capture

This tarball was regenerated from a placeholder spec using real screen capture
and DepthAnything inference.

## Provenance

- **Video**: Real screen capture ({capture_info.get('duration_sec', 'unknown')}s at {capture_info.get('fps', 30)}fps)
- **Depth**: {depth_info.get('frames_inferred', 'unknown')} frames inferred via DepthAnything V2

## Integrity

All files are real captures or derived from real captures. No placeholders.

Generated by `bin/buyer_tarball_make_real.py`.
"""
    readme.write_text(content)


def _repack(staging: Path, output_tar: Path) -> None:
    """Step 6 — tar the staging dir to output_tar."""
    output_tar.parent.mkdir(parents=True, exist_ok=True)
    with tarfile.open(output_tar, "w:gz") as tar:
        tar.add(staging, arcname=staging.name)


def make_real_tarball(
    in_tarball: Path,
    out_tarball: Path,
    *,
    region: tuple[int, int, int, int],
    duration: float,
) -> dict[str, Any]:
    """Replace placeholder video and depth in a buyer-spec tarball with real captures.
    
    Extracts the input tarball to a temporary staging directory, replaces
    ``video.mp4`` with a real screen capture, regenerates depth EXR frames
    via DepthAnything inference, recomputes SHA256 checksums, writes a
    truthful README, and repacks into the output tarball.
    
    Args:
        in_tarball: Path to the input tarball containing placeholder media.
        out_tarball: Path where the rebuilt tarball with real captures will
            be written.
        region: A 4-tuple of ``(x, y, width, height)`` specifying the screen
            capture region in pixels.
        duration: Number of seconds to capture for the screen recording.
    
    Returns:
        A dictionary with keys ``input``, ``output``, ``size_bytes``,
        ``video``, and ``depth`` describing the result.
    
    Raises:
        FileNotFoundError: If ``in_tarball`` does not exist.
        RuntimeError: If the tarball has an unexpected layout, or if
            video capture or depth inference produces unusable output.
    """
    if not in_tarball.exists():
        raise FileNotFoundError(f"input tarball missing: {in_tarball}")

    work = Path(tempfile.mkdtemp(prefix="buyer_real_"))
    try:
        # 1. extract
        with tarfile.open(in_tarball, "r:gz") as tar:
            tar.extractall(work)
        # find the staging root (single directory inside)
        roots = [p for p in work.iterdir() if p.is_dir()]
        if len(roots) != 1:
            raise RuntimeError(f"unexpected tarball layout — {len(roots)} top-level dirs")
        staging = roots[0]

        # 2. real video
        capture_info = _replace_video(staging, region=region, duration=duration)
        # 3. real depth
        depth_info = _replace_depth(staging)
        # 4. fresh sha256
        _recompute_sha256sums(staging)
        # 5. truthful readme
        _write_truthful_readme(staging, capture_info=capture_info, depth_info=depth_info)
        # 6. repack
        _repack(staging, out_tarball)

        return {
            "input": str(in_tarball),
            "output": str(out_tarball),
            "size_bytes": out_tarball.stat().st_size,
            "video": capture_info,
            "depth": depth_info,
        }
    finally:
        shutil.rmtree(work, ignore_errors=True)


def main(argv: list[str] | None = None) -> int:
    """Command-line entry point for rebuilding buyer tarballs with real captures.
    
    Parses command-line arguments for input/output tarball paths and capture
    configuration, then delegates to :func:`make_real_tarball` for the actual
    processing.
    
    Args:
        argv: Optional list of command-line arguments. If ``None``, arguments
            are taken from ``sys.argv``.
    
    Returns:
        Exit code: 0 on success, 2 on argument validation error.
    """
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--in-tarball", type=Path, required=True)
    p.add_argument("--out-tarball", type=Path, required=True)
    p.add_argument("--capture-region", type=str, default="0,0,1920,1080",
                   help="x,y,w,h pixel region (default primary monitor 1920×1080)")
    p.add_argument("--capture-duration", type=float, default=300.0,
                   help="seconds to capture (default 300 = 5 min for buyer spec)")
    args = p.parse_args(argv)

    region = tuple(int(x) for x in args.capture_region.split(","))
    if len(region) != 4:
        print("ERROR: --capture-region must be x,y,w,h", file=sys.stderr)
        return 2

    info = make_real_tarball(
        args.in_tarball, args.out_tarball,
        region=region, duration=args.capture_duration,
    )
    print(json.dumps(info, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())